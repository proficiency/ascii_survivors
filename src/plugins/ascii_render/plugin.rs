use crate::resources::{CameraOffset, SceneLock};

const DEFAULT_CELL_SIZE: Vec2 = Vec2::new(16.0, 16.0);

pub struct AsciiRenderPlugin;

impl Plugin for AsciiRenderPlugin {
    fn build(&self, app: &mut App) {
        app.add_systems(Startup, setup_ascii_renderer)
            .add_systems(
                Startup,
                crate::plugins::rendering::setup_lighting_overlay.after(setup_ascii_renderer),
            )
            .add_systems(Update, resize_ascii_grid)
            .add_systems(
                Update,
                update_cinematic_target.before(update_cinematic_camera),
            )
            .add_systems(Update, update_cinematic_camera)
            .add_systems(
                Update,
                render_ascii_canvas.in_set(crate::plugins::core::GameSet::Rendering),
            );
    }
}

#[derive(Resource)]
struct AsciiCanvas {
    handle: Handle<Image>,
    pixel_size: UVec2,
    cell_size: UVec2,
    prev_cells: Vec<crate::resources::AsciiCell>,
}

#[derive(Component)]
struct AsciiCanvasSprite;

fn setup_ascii_renderer(
    mut commands: Commands,
    windows: Query<&Window, With<PrimaryWindow>>,
    mut images: ResMut<Assets<Image>>,
) {
    let window = windows
        .single()
        .expect("primary window should exist before renderer setup");
    let cell_size = DEFAULT_CELL_SIZE;
    let grid_size = compute_grid_size(window, cell_size);
    let grid = AsciiGrid {
        cell_size,
        grid_size,
    };
    commands.insert_resource(grid);
    commands.insert_resource(AsciiFrame::new(grid_size));

    commands.insert_resource(CinematicCamera::default());
    commands.spawn((
        Camera2d,
        Transform::from_xyz(grid.world_center().x, grid.world_center().y, 999.0),
    ));

    let (canvas, sprite_entity) = spawn_ascii_canvas(&mut commands, &grid, &mut images);
    commands.insert_resource(canvas);
    commands.entity(sprite_entity).insert(AsciiCanvasSprite);
}

fn resize_ascii_grid(
    mut commands: Commands,
    windows: Query<&Window, With<PrimaryWindow>>,
    mut grid: ResMut<AsciiGrid>,
    mut frame: ResMut<AsciiFrame>,
    mut canvas: ResMut<AsciiCanvas>,
    mut sprite_query: Query<(&mut Sprite, &mut Transform), With<AsciiCanvasSprite>>,
    mut images: ResMut<Assets<Image>>,
) {
    let window = match windows.single() {
        Ok(window) => window,
        Err(_) => return,
    };

    let new_size = compute_grid_size(window, grid.cell_size);
    if new_size == grid.grid_size {
        return;
    }

    grid.grid_size = new_size;
    frame.resize(new_size);
    resize_ascii_canvas(
        &mut commands,
        &grid,
        &mut canvas,
        &mut sprite_query,
        &mut images,
    );
}

fn update_cinematic_camera(
    time: Res<Time>,
    mut cinematic: ResMut<CinematicCamera>,
    mut camera_offset: ResMut<CameraOffset>,
) {
    let delta = time.delta_secs();
    let smoothing = cinematic.smoothing.max(0.0);
    let t = if smoothing <= f32::EPSILON {
        1.0
    } else {
        1.0 - (-smoothing * delta).exp()
    };
    cinematic.current_offset = cinematic.current_offset.lerp(cinematic.target_offset, t);

    camera_offset.0 = IVec2::new(
        cinematic.current_offset.x.floor() as i32,
        cinematic.current_offset.y.floor() as i32,
    );
}

fn update_cinematic_target(
    grid: Res<AsciiGrid>,
    scene_lock: Res<SceneLock>,
    player_query: Query<&GridPosition, With<PlayerTag>>,
    camera_offset: Res<CameraOffset>,
    mut cinematic: ResMut<CinematicCamera>,
) {
    if scene_lock.0 {
        let locked = camera_offset.0.as_vec2();
        cinematic.target_offset = locked;
        cinematic.current_offset = locked;
        return;
    }

    if let Ok(pos) = player_query.single() {
        let center = IVec2::new((grid.grid_size.x / 2) as i32, (grid.grid_size.y / 2) as i32);
        let target = pos.world - center;
        cinematic.target_offset = target.as_vec2();
    }
}

fn render_ascii_canvas(
    frame: Res<AsciiFrame>,
    mut canvas: ResMut<AsciiCanvas>,
    mut images: ResMut<Assets<Image>>,
) {
    let Some(image) = images.get_mut(&canvas.handle) else {
        return;
    };
    let Some(data) = image.data.as_mut() else {
        return;
    };

    let cell_size = canvas.cell_size;
    let grid_size = frame.size;
    let width = canvas.pixel_size.x as usize;
    let height = canvas.pixel_size.y as usize;
    let scale_x = (cell_size.x / 8).max(1);
    let scale_y = (cell_size.y / 8).max(1);

    if data.len() != width * height * 4 {
        return;
    }

    if canvas.prev_cells.len() != frame.cells.len() {
        canvas.prev_cells = vec![crate::resources::AsciiCell::default(); frame.cells.len()];
    }

    for (index, cell) in frame.cells.iter().enumerate() {
        if canvas.prev_cells[index] == *cell {
            continue;
        }

        canvas.prev_cells[index] = *cell;

        let x = (index as u32) % grid_size.x;
        let y = (index as u32) / grid_size.x;
        let base_x = x * cell_size.x;
        let base_y = y * cell_size.y;
        if base_x + cell_size.x > canvas.pixel_size.x || base_y + cell_size.y > canvas.pixel_size.y
        {
            continue;
        }

        fill_cell(data, width, base_x, base_y, cell_size, cell.bg);

        if cell.ch != ' ' {
            draw_glyph(
                data, width, base_x, base_y, scale_x, scale_y, cell.ch, cell.fg,
            );
        }
    }
}

fn compute_grid_size(window: &Window, cell_size: Vec2) -> UVec2 {
    let width = (window.resolution.width() / cell_size.x).floor() as u32;
    let height = (window.resolution.height() / cell_size.y).floor() as u32;
    UVec2::new(width.max(1), height.max(1))
}

fn spawn_ascii_canvas(
    commands: &mut Commands,
    grid: &AsciiGrid,
    image_assets: &mut Assets<Image>,
) -> (AsciiCanvas, Entity) {
    let cell_size = UVec2::new(grid.cell_size.x as u32, grid.cell_size.y as u32);
    let pixel_size = UVec2::new(
        grid.grid_size.x * cell_size.x,
        grid.grid_size.y * cell_size.y,
    );
    let pixel_count = (pixel_size.x * pixel_size.y * 4) as usize;
    let mut image = Image::new_fill(
        Extent3d {
            width: pixel_size.x,
            height: pixel_size.y,
            depth_or_array_layers: 1,
        },
        TextureDimension::D2,
        &[0, 0, 0, 255],
        TextureFormat::Rgba8UnormSrgb,
        RenderAssetUsages::RENDER_WORLD | RenderAssetUsages::MAIN_WORLD,
    );
    image.texture_descriptor.usage |= TextureUsages::COPY_DST;
    image.data = Some(vec![0; pixel_count]);

    let handle = image_assets.add(image);

    let mut sprite = Sprite::from_image(handle.clone());
    sprite.custom_size = Some(grid.world_size());

    let entity = commands
        .spawn((
            sprite,
            Transform::from_xyz(grid.world_center().x, grid.world_center().y, 0.0),
            Name::new("AsciiCanvas"),
        ))
        .id();

    (
        AsciiCanvas {
            handle,
            pixel_size,
            cell_size,
            prev_cells: vec![
                crate::resources::AsciiCell::default();
                (grid.grid_size.x * grid.grid_size.y) as usize
            ],
        },
        entity,
    )
}

fn resize_ascii_canvas(
    commands: &mut Commands,
    grid: &AsciiGrid,
    canvas: &mut AsciiCanvas,
    sprite_query: &mut Query<(&mut Sprite, &mut Transform), With<AsciiCanvasSprite>>,
    images: &mut Assets<Image>,
) {
    let cell_size = UVec2::new(grid.cell_size.x as u32, grid.cell_size.y as u32);
    let pixel_size = UVec2::new(
        grid.grid_size.x * cell_size.x,
        grid.grid_size.y * cell_size.y,
    );
    if pixel_size == canvas.pixel_size {
        return;
    }

    let pixel_count = (pixel_size.x * pixel_size.y * 4) as usize;
    let mut image = Image::new_fill(
        Extent3d {
            width: pixel_size.x,
            height: pixel_size.y,
            depth_or_array_layers: 1,
        },
        TextureDimension::D2,
        &[0, 0, 0, 255],
        TextureFormat::Rgba8UnormSrgb,
        RenderAssetUsages::RENDER_WORLD | RenderAssetUsages::MAIN_WORLD,
    );
    image.texture_descriptor.usage |= TextureUsages::COPY_DST;
    image.data = Some(vec![0; pixel_count]);
    let handle = images.add(image);

    canvas.handle = handle.clone();
    canvas.pixel_size = pixel_size;
    canvas.cell_size = cell_size;
    canvas.prev_cells = vec![
        crate::resources::AsciiCell::default();
        (grid.grid_size.x * grid.grid_size.y) as usize
    ];

    if let Ok((mut sprite, mut transform)) = sprite_query.single_mut() {
        sprite.image = handle;
        sprite.custom_size = Some(grid.world_size());
        transform.translation = Vec3::new(grid.world_center().x, grid.world_center().y, 0.0);
    } else {
        let mut sprite = Sprite::from_image(handle);
        sprite.custom_size = Some(grid.world_size());
        let entity = commands
            .spawn((
                AsciiCanvasSprite,
                sprite,
                Transform::from_xyz(grid.world_center().x, grid.world_center().y, 0.0),
                Name::new("AsciiCanvas"),
            ))
            .id();
        commands.entity(entity);
    }
}

fn fill_cell(
    data: &mut [u8],
    width: usize,
    base_x: u32,
    base_y: u32,
    cell_size: UVec2,
    color: Color,
) {
    let srgb = color.to_srgba();
    let r = (srgb.red.clamp(0.0, 1.0) * 255.0) as u8;
    let g = (srgb.green.clamp(0.0, 1.0) * 255.0) as u8;
    let b = (srgb.blue.clamp(0.0, 1.0) * 255.0) as u8;
    let a = (srgb.alpha.clamp(0.0, 1.0) * 255.0) as u8;

    for y in 0..cell_size.y {
        let row = (base_y + y) as usize;
        let start = (row * width + base_x as usize) * 4;
        let end = start + cell_size.x as usize * 4;
        for chunk in data[start..end].chunks_exact_mut(4) {
            chunk[0] = r;
            chunk[1] = g;
            chunk[2] = b;
            chunk[3] = a;
        }
    }
}

fn draw_glyph(
    data: &mut [u8],
    width: usize,
    base_x: u32,
    base_y: u32,
    scale_x: u32,
    scale_y: u32,
    ch: char,
    color: Color,
) {
    let glyph = glyph_bitmap(ch);
    let srgb = color.to_srgba();
    let r = (srgb.red.clamp(0.0, 1.0) * 255.0) as u8;
    let g = (srgb.green.clamp(0.0, 1.0) * 255.0) as u8;
    let b = (srgb.blue.clamp(0.0, 1.0) * 255.0) as u8;
    let a = (srgb.alpha.clamp(0.0, 1.0) * 255.0) as u8;

    for (row, bits) in glyph.iter().enumerate() {
        for col in 0..8 {
            if (bits >> (7 - col)) & 1 == 0 {
                continue;
            }
            let px = base_x + (col as u32 * scale_x);
            let py = base_y + (row as u32 * scale_y);
            for dy in 0..scale_y {
                let row_index = (py + dy) as usize;
                let start = (row_index * width + px as usize) * 4;
                let end = start + scale_x as usize * 4;
                for chunk in data[start..end].chunks_exact_mut(4) {
                    chunk[0] = r;
                    chunk[1] = g;
                    chunk[2] = b;
                    chunk[3] = a;
                }
            }
        }
    }
}

fn glyph_bitmap(ch: char) -> [u8; 8] {
    let idx = ch as usize;
    if idx < FONT8X8_BASIC.len() {
        FONT8X8_BASIC[idx]
    } else {
        FONT8X8_BASIC[b'?' as usize]
    }
}

